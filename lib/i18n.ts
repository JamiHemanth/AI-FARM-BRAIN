export function detectLanguage(question: string, fallback: Language): Language {
  if (/[\u0C00-\u0C7F]/.test(question)) return "te";
  if (/[\u0900-\u097F]/.test(question)) return "hi";
  return fallback;
}

export function useI18n() {
  const [language, setLanguageState] = useState<Language>("en");
  useEffect(() => {
    const stored = window.localStorage.getItem("farmbrain-language") as Language | null;
    if (stored === "te" || stored === "hi" || stored === "en") setLanguageState(stored);
    const onChange = (event: Event) => {
      const custom = event as CustomEvent<Language>;
      if (custom.detail) setLanguageState(custom.detail);
    };
    window.addEventListener("farmbrain-language-change", onChange);
    return () => window.removeEventListener("farmbrain-language-change", onChange);
  }, []);
  const api = useMemo(() => ({
    language,
    setLanguage(next: Language) {
      setLanguageState(next);
      window.localStorage.setItem("farmbrain-language", next);
      window.dispatchEvent(new CustomEvent("farmbrain-language-change", { detail: next }));
    },
    t(value: string) {
      return translate(language, value);
    },
    tx(value?: string | null) {
      return translate(language, value);
    }
  }), [language]);
  return api;
}
